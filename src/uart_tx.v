// ============================================================================
// Модуль:      uart_tx
// Призначення: Передавач UART (формат кадру 8N1: 1 старт-біт, 8 біт даних,
//              без біта парності, 1 стоп-біт). Дані передаються молодшим
//              бітом (LSB) вперед.
// Принцип:     Скінченний автомат (FSM) IDLE -> START -> DATA -> STOP -> DONE.
//              Тривалість одного біта задається вбудованим дільником тактової
//              частоти (лічильник clk_cnt рахує CLKS_PER_BIT тактів).
// ============================================================================
`timescale 1ns / 1ps

module uart_tx #(
    parameter integer CLK_FREQ  = 50_000_000,  // Тактова частота, Гц
    parameter integer BAUD_RATE = 115_200      // Баудова швидкість, біт/с
)(
    input  wire       clk,       // Системний тактовий сигнал
    input  wire       rst,       // Синхронне скидання, активний рівень '1'
    input  wire       tx_start,  // Імпульс запуску передачі (1 такт)
    input  wire [7:0] tx_data,   // Байт для передачі
    output reg        tx,        // Послідовний вихід UART (TxD), у спокої '1'
    output reg        tx_busy,   // '1' поки триває передача кадру
    output reg        tx_done    // Імпульс '1' на 1 такт після завершення кадру
);

    // ------------------------------------------------------------------------
    // Дільник частоти: кількість тактів clk на один біт UART.
    // 50 000 000 / 115 200 = 434 (похибка ~0.06 %, допустимо < 2 %)
    // ------------------------------------------------------------------------
    localparam integer CLKS_PER_BIT = CLK_FREQ / BAUD_RATE;
    localparam integer CNT_W        = $clog2(CLKS_PER_BIT);

    // ------------------------------------------------------------------------
    // Кодування станів FSM
    // ------------------------------------------------------------------------
    localparam [2:0] S_IDLE  = 3'd0,  // Очікування tx_start, лінія = '1'
                     S_START = 3'd1,  // Передача старт-біта ('0')
                     S_DATA  = 3'd2,  // Передача 8 біт даних
                     S_STOP  = 3'd3,  // Передача стоп-біта ('1')
                     S_DONE  = 3'd4;  // Формування імпульсу tx_done

    // ------------------------------------------------------------------------
    // Внутрішні регістри
    // ------------------------------------------------------------------------
    reg [2:0]       state;     // Поточний стан автомата
    reg [CNT_W-1:0] clk_cnt;   // Лічильник тактів усередині одного біта
    reg [2:0]       bit_idx;   // Номер біта даних, що передається (0..7)
    reg [7:0]       data_reg;  // Збережена копія байта на час передачі

    // ------------------------------------------------------------------------
    // Основний процес: FSM + дільник частоти
    // ------------------------------------------------------------------------
    always @(posedge clk) begin
        if (rst) begin
            state    <= S_IDLE;
            clk_cnt  <= 0;
            bit_idx  <= 0;
            data_reg <= 8'h00;
            tx       <= 1'b1;   // Лінія UART у спокої - високий рівень
            tx_busy  <= 1'b0;
            tx_done  <= 1'b0;
        end else begin
            tx_done <= 1'b0;    // За замовчуванням імпульс знятий

            case (state)
                // ---------------- Очікування команди ----------------
                S_IDLE: begin
                    tx      <= 1'b1;
                    clk_cnt <= 0;
                    bit_idx <= 0;
                    if (tx_start) begin
                        data_reg <= tx_data;  // Фіксуємо байт
                        tx_busy  <= 1'b1;
                        state    <= S_START;
                    end
                end

                // ---------------- Старт-біт ----------------
                S_START: begin
                    tx <= 1'b0;
                    if (clk_cnt == CLKS_PER_BIT - 1) begin
                        clk_cnt <= 0;
                        state   <= S_DATA;
                    end else
                        clk_cnt <= clk_cnt + 1'b1;
                end

                // ---------------- Біти даних (LSB first) ----------------
                S_DATA: begin
                    tx <= data_reg[bit_idx];
                    if (clk_cnt == CLKS_PER_BIT - 1) begin
                        clk_cnt <= 0;
                        if (bit_idx == 3'd7) begin
                            bit_idx <= 0;
                            state   <= S_STOP;
                        end else
                            bit_idx <= bit_idx + 1'b1;
                    end else
                        clk_cnt <= clk_cnt + 1'b1;
                end

                // ---------------- Стоп-біт ----------------
                S_STOP: begin
                    tx <= 1'b1;
                    if (clk_cnt == CLKS_PER_BIT - 1) begin
                        clk_cnt <= 0;
                        state   <= S_DONE;
                    end else
                        clk_cnt <= clk_cnt + 1'b1;
                end

                // ---------------- Завершення ----------------
                S_DONE: begin
                    tx      <= 1'b1;
                    tx_done <= 1'b1;
                    tx_busy <= 1'b0;
                    state   <= S_IDLE;
                end

                default: state <= S_IDLE;
            endcase
        end
    end

endmodule
