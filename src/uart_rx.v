// ============================================================================
// Модуль:      uart_rx
// Призначення: Приймач UART (формат 8N1, LSB first).
// Принцип:     1) Вхід rx синхронізується двома тригерами (захист від
//                 метастабільності, бо сигнал асинхронний до clk).
//              2) Після спаду лінії (початок старт-біта) чекаємо пів біта і
//                 перевіряємо, що лінія досі '0' - це середина старт-біта.
//              3) Далі кожні CLKS_PER_BIT тактів зчитуємо біт - щоразу
//                 потрапляємо в середину бітового інтервалу.
//              4) Перевіряємо стоп-біт ('1'), інакше - помилка кадру.
// ============================================================================
module uart_rx #(
    parameter integer CLK_FREQ  = 50_000_000,  // Тактова частота, Гц
    parameter integer BAUD_RATE = 115_200      // Баудова швидкість, біт/с
)(
    input  wire       clk,          // Системний тактовий сигнал
    input  wire       rst,          // Синхронне скидання, активний рівень '1'
    input  wire       rx,           // Послідовний вхід UART (RxD)
    output reg  [7:0] rx_data,      // Прийнятий байт
    output reg        rx_valid,     // Імпульс '1' на 1 такт: rx_data готові
    output reg        frame_error   // Імпульс '1': стоп-біт не дорівнює '1'
);

    // ------------------------------------------------------------------------
    // Дільник частоти
    // ------------------------------------------------------------------------
    localparam integer CLKS_PER_BIT  = CLK_FREQ / BAUD_RATE;  // 434
    localparam integer HALF_BIT      = CLKS_PER_BIT / 2;      // 217
    localparam integer CNT_W         = $clog2(CLKS_PER_BIT);

    // ------------------------------------------------------------------------
    // Кодування станів FSM
    // ------------------------------------------------------------------------
    localparam [2:0] S_IDLE  = 3'd0,  // Очікування спаду лінії
                     S_START = 3'd1,  // Перевірка середини старт-біта
                     S_DATA  = 3'd2,  // Прийом 8 біт даних
                     S_STOP  = 3'd3,  // Перевірка стоп-біта
                     S_DONE  = 3'd4;  // Очікування повернення лінії в '1'

    // ------------------------------------------------------------------------
    // Синхронізатор вхідного сигналу (2 тригери)
    // Початкове значення '1' - щоб після скидання не побачити хибний старт.
    // ------------------------------------------------------------------------
    reg rx_meta = 1'b1;  // Перший тригер (може бути метастабільним)
    reg rx_sync = 1'b1;  // Другий тригер - стабільний сигнал для логіки

    always @(posedge clk) begin
        rx_meta <= rx;
        rx_sync <= rx_meta;
    end

    // ------------------------------------------------------------------------
    // Внутрішні регістри
    // ------------------------------------------------------------------------
    reg [2:0]       state;     // Поточний стан автомата
    reg [CNT_W-1:0] clk_cnt;   // Лічильник тактів усередині біта
    reg [2:0]       bit_idx;   // Номер біта, що приймається (0..7)
    reg [7:0]       shift_reg; // Регістр збирання прийнятих біт

    // ------------------------------------------------------------------------
    // Основний процес: FSM приймача
    // ------------------------------------------------------------------------
    always @(posedge clk) begin
        if (rst) begin
            state       <= S_IDLE;
            clk_cnt     <= 0;
            bit_idx     <= 0;
            shift_reg   <= 8'h00;
            rx_data     <= 8'h00;
            rx_valid    <= 1'b0;
            frame_error <= 1'b0;
        end else begin
            rx_valid    <= 1'b0;  // Імпульсні виходи за замовчуванням знято
            frame_error <= 1'b0;

            case (state)
                // ---------------- Очікування старт-біта ----------------
                S_IDLE: begin
                    clk_cnt <= 0;
                    bit_idx <= 0;
                    if (rx_sync == 1'b0)       // Виявлено спад лінії
                        state <= S_START;
                end

                // ---------------- Середина старт-біта ----------------
                S_START: begin
                    if (clk_cnt == HALF_BIT - 1) begin
                        clk_cnt <= 0;
                        if (rx_sync == 1'b0)   // Справжній старт-біт
                            state <= S_DATA;
                        else                   // Короткий імпульс-завада
                            state <= S_IDLE;
                    end else
                        clk_cnt <= clk_cnt + 1'b1;
                end

                // ---------------- Прийом біт даних ----------------
                S_DATA: begin
                    if (clk_cnt == CLKS_PER_BIT - 1) begin
                        clk_cnt            <= 0;
                        shift_reg[bit_idx] <= rx_sync;  // Семпл у середині біта
                        if (bit_idx == 3'd7) begin
                            bit_idx <= 0;
                            state   <= S_STOP;
                        end else
                            bit_idx <= bit_idx + 1'b1;
                    end else
                        clk_cnt <= clk_cnt + 1'b1;
                end

                // ---------------- Стоп-біт ----------------
                S_STOP: begin
                    if (clk_cnt == CLKS_PER_BIT - 1) begin
                        clk_cnt <= 0;
                        if (rx_sync == 1'b1) begin   // Коректний стоп-біт
                            rx_data  <= shift_reg;   // Видаємо байт
                            rx_valid <= 1'b1;
                        end else
                            frame_error <= 1'b1;     // Помилка кадру
                        state <= S_DONE;
                    end else
                        clk_cnt <= clk_cnt + 1'b1;
                end

                // ---------------- Завершення кадру ----------------
                S_DONE: begin
                    // Чекаємо, поки лінія повернеться в '1', щоб не
                    // сприйняти "застряглий" нуль як новий старт-біт
                    if (rx_sync == 1'b1)
                        state <= S_IDLE;
                    else
                        state <= S_DONE;
                end

                default: state <= S_IDLE;
            endcase
        end
    end

endmodule
